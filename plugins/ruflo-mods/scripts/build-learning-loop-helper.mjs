#!/usr/bin/env node
// Bundles the classic-hooks learning loop (ADR-512) into .claude/helpers/learning-loop.cjs, from the mod's own loop
// source (scripts/learning-loop-helper.ts → hooks/loop/transcript.ts), so classic hooks and the mod decide outcomes and
// pick lessons with one implementation. The bundle is committed: helper-refresh copies the package's helpers into
// every project on its next `ruflo` command, and the release signs them. esbuild is a BUILD-time tool only.
//   node plugins/ruflo-mods/scripts/build-learning-loop-helper.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repo = resolve(root, '..', '..')
const check = process.argv.includes('--check')
const targets = [join(repo, 'v3', '@claude-flow', 'cli', '.claude', 'helpers', 'learning-loop.cjs'), join(repo, '.claude', 'helpers', 'learning-loop.cjs')]

// The repo's own esbuild (npm install at the root), or the one in RUFLO_ESBUILD_DIR (as build-tui.mjs).
let esbuild
for (const base of [join(repo, 'package.json'), join(repo, 'v3', 'package.json'), ...(process.env.RUFLO_ESBUILD_DIR ? [join(process.env.RUFLO_ESBUILD_DIR, 'package.json')] : [])]) {
  try {
    esbuild = createRequire(base)('esbuild')
    break
  } catch {
    // try the next place
  }
}
if (esbuild === undefined) {
  console.error('build-learning-loop-helper: esbuild is not installed (npm install at the repo root, or set RUFLO_ESBUILD_DIR).')
  process.exit(1)
}

const result = await esbuild.build({
  entryPoints: [join(root, 'scripts', 'learning-loop-helper.ts')],
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node20',
  minify: false,
  legalComments: 'none',
  write: false,
  absWorkingDir: repo,
  logLevel: 'warning',
  banner: { js: '// GENERATED by plugins/ruflo-mods/scripts/build-learning-loop-helper.mjs from the ruflo-mods learning loop (ADR-512). Do not edit.' },
})
// esbuild writes the entry's path into a comment; keep the bundle the same on every machine.
const text = result.outputFiles[0].text.replaceAll(repo.replace(/\\/g, '/') + '/', '')

let stale = 0
for (const target of targets) {
  let current = null
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    // missing
  }
  if (current === text) continue
  if (check) {
    console.error(`build-learning-loop-helper: ${target} is stale; run node plugins/ruflo-mods/scripts/build-learning-loop-helper.mjs`)
    stale++
  } else {
    writeFileSync(target, text)
    console.log(`build-learning-loop-helper: wrote ${target} (${Math.round(text.length / 1024)} KiB)`)
  }
}
process.exit(stale ? 1 : 0)
